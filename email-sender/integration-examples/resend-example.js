/**
 * Okiza Email Sending with Resend (JavaScript)
 *
 * Requirements:
 *   npm install resend
 *
 * Setup:
 *   Set your RESEND_API_KEY environment variable.
 */

const { Resend } = require('resend');
const { renderEmail, getMissingPlaceholders } = require('../utils/template-loader');

// Initialize Resend client
const resend = new Resend(process.env.RESEND_API_KEY || 're_test_dummy_key');

/**
 * 1. Send General Notification
 */
async function sendGeneralNotification({ to, recipientName, subject, message, buttonText, buttonUrl }) {
  const html = renderEmail('general-notification', {
    recipientName,
    subject,
    message,
    buttonText,
    buttonUrl,
  });

  return await resend.emails.send({
    from: 'Okiza <notifications@okiza.ai>',
    to,
    subject,
    html,
  });
}

